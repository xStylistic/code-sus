# Language syntax guides — inlined into system messages to avoid extra API calls.
# Previously these were tool calls, but each tool call doubles the Gemini API
# usage (one call to decide to use the tool, another to process the result).
SYNTAX_GUIDES = {
    "javascript": """JavaScript OOP:
- Class: class Animal { constructor(name) { this.name = name; } speak() { return this.name; } }
- Inheritance: class Dog extends Animal { constructor(name) { super(name); } }
- Private: use #field syntax or closures. Use #balance for private fields.
- Polymorphism: override methods in subclass, no keyword needed""",

    "python": """Python OOP:
- Class: class Animal: def __init__(self, name): self.name = name
- Inheritance: class Dog(Animal): def __init__(self, name): super().__init__(name)
- Private: prefix with underscore _balance (convention) or __balance (name mangling)
- Polymorphism: override methods in subclass, no keyword needed""",

    "java": """Java OOP:
- Class: public class Animal { String name; Animal(String name) { this.name = name; } }
- Inheritance: public class Dog extends Animal { Dog(String name) { super(name); } }
- Private: private int balance; with public getBalance() method
- Polymorphism: @Override annotation, method overriding""",

    "cpp": """C++ OOP:
- Class: class Animal { public: string name; Animal(string name) : name(name) {} };
- Inheritance: class Dog : public Animal { public: Dog(string name) : Animal(name) {} };
- Private: private: section with public getter methods
- Polymorphism: virtual methods, override keyword""",

    "c": """C OOP (struct-based):
- Struct: typedef struct { char* name; } Animal;
- Inheritance: embed base struct: typedef struct { Animal base; } Dog;
- Encapsulation: opaque struct with accessor functions
- Polymorphism: function pointers in struct"""
}


def get_syntax_guide(language: str) -> str:
    """Get OOP syntax reference for a programming language."""
    return SYNTAX_GUIDES.get(language, SYNTAX_GUIDES["javascript"])


@rt.function_node
def validate_code_patterns(code: str, patterns: list) -> dict:
    """Check if code contains all required patterns for task validation.

    Args:
        code (str): The source code to validate.
        patterns (list): List of string patterns that should appear in the code.
    """
    results = []
    for pattern in patterns:
        found = pattern.strip() in code.replace("  ", " ").strip()
        results.append({"pattern": pattern, "found": found})

    all_passed = all(r["found"] for r in results)
    return {
        "passed": all_passed,
        "results": results,
        "summary": "All checks passed." if all_passed else "Some patterns are missing."
    }


