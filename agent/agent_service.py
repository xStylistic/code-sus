# ── Endpoint 1: Generate a coding task ────────────────────────────────────────
@app.post("/api/generate-task")
async def generate_task(request: GenerateTaskRequest):
    """Generate an AI-powered OOP coding task.

    Uses the Task Generator agent with Pydantic structured output to return
    a fully typed CodingTask object with prompt, starter code, solution, and checks.
    """
    try:
        syntax = get_syntax_guide(request.language)
        prompt = (
            f"Generate a {request.task_type} coding task in {request.language}.\n\n"
            f"Language syntax reference:\n{syntax}\n\n"
            f"The task should teach the concept of {request.task_type} through a "
            f"creative, original scenario (don't use Animal/Dog or BankAccount — "
            f"pick something unique and fun)."
        )

        result = await call_with_retry(task_generator, prompt)
        task = result.structured

        return {
            "ok": True,
            "task": task.model_dump()
        }
    except Exception as e:
        logger.error(f"/api/generate-task failed: {e}")
        return {"ok": False, "error": str(e)}


# ── Endpoint 2: Get imposter sabotage hints ──────────────────────────────────
@app.post("/api/imposter-hints")
async def get_imposter_hints(request: ImposterHintsRequest):
    """Generate 1 sabotage code suggestion for the imposter.

    Uses the Imposter Advisor agent with structured output to return
    a plausible but inefficient/bad-practice code variant.
    """
    try:
        syntax = get_syntax_guide(request.language)
        prompt = (
            f"Generate 1 sabotage suggestion for an {request.task_type} task "
            f"in {request.language}.\n\n"
            f"Language syntax reference:\n{syntax}\n\n"
            f"Task prompt: {request.prompt}\n\n"
            f"Current code in the editor:\n```\n{request.current_code}\n```\n\n"
            f"Generate 1 code variant that looks like real work but uses bad practices "
            f"or is subtly inefficient. The code_snippet should be the full file content. "
            f"The bad_practice should explain in 1-2 sentences why this code is problematic."
        )

        result = await call_with_retry(imposter_advisor, prompt)
        hints = result.structured

        return {
            "ok": True,
            "hints": [h.model_dump() for h in hints.hints]
        }
    except Exception as e:
        logger.error(f"/api/imposter-hints failed: {e}")
        return {"ok": False, "error": str(e)}


# ── Endpoint 3: AI code verification ─────────────────────────────────────────
@app.post("/api/verify-code")
async def verify_code(request: VerifyCodeRequest):
    """AI-powered code review for task submissions.

    Uses the Code Verifier agent to check if submitted code correctly
    implements the OOP concept, providing detailed feedback.
    """
    try:
        prompt = (
            f"Verify this {request.task_type} code in {request.language}.\n\n"
            f"Task: {request.task_prompt}\n\n"
            f"Submitted code:\n```\n{request.code}\n```\n\n"
            f"Does this code correctly implement the {request.task_type} concept? "
            f"Check for proper OOP usage."
        )

        result = await call_with_retry(code_verifier, prompt)
        verification = result.structured

        return {
            "ok": True,
            "verification": verification.model_dump()
        }
    except Exception as e:
        logger.error(f"/api/verify-code failed: {e}")
        return {"ok": False, "error": str(e)}


# ── Endpoint 4: Meeting behavior analysis (Add-on Feature) ──────────────────
@app.post("/api/meeting-insights")
async def meeting_insights(request: MeetingInsightRequest):
    """AI analysis of player behavior for emergency meetings.

    Add-on feature: analyzes who edited what, task progress, and sabotage
    events to generate discussion prompts for the crew.
    """
    try:
        player_summary = "\n".join([
            f"- {p.get('name', 'Unknown')}: "
            f"{'alive' if p.get('isAlive', True) else 'eliminated'}, "
            f"{len(p.get('completedTasks', []))} tasks completed"
            for p in request.players
        ])

        editor_summary = "\n".join([
            f"- Task {tid}: edited by {', '.join(editors)}"
            for tid, editors in request.task_editors.items()
            if editors
        ]) or "No editing data available"

        prompt = (
            f"Analyze this game state for an emergency meeting:\n\n"
            f"Players:\n{player_summary}\n\n"
            f"Task editors:\n{editor_summary}\n\n"
            f"Team progress: {request.task_progress * 100:.0f}%\n"
            f"Sabotage pressure: {request.disruption}/4\n\n"
            f"Generate discussion prompts to help the crew identify the imposter."
        )

        result = await call_with_retry(meeting_analyst, prompt)
        insight = result.structured

        return {
            "ok": True,
            "insight": insight.model_dump()
        }
    except Exception as e:
        logger.error(f"/api/meeting-insights failed: {e}")
        return {"ok": False, "error": str(e)}


