async def call_with_retry(agent, prompt, max_retries=2):
    """Call a Railtracks agent with retry logic for rate limit (429) errors."""
    for attempt in range(max_retries + 1):
        try:
            logger.info(f"Calling agent '{agent.name}' (attempt {attempt + 1}/{max_retries + 1})")
            result = await rt.call(agent, prompt)
            logger.info(f"Agent '{agent.name}' returned successfully")
            return result
        except Exception as e:
            error_str = str(e).lower()
            is_rate_limit = "429" in error_str or "rate" in error_str or "quota" in error_str or "resource_exhausted" in error_str
            if is_rate_limit and attempt < max_retries:
                wait_time = 5 * (attempt + 1)  # 5s, 10s
                logger.warning(f"Rate limited on attempt {attempt + 1}. Waiting {wait_time}s before retry...")
                await asyncio.sleep(wait_time)
            else:
                logger.error(f"Agent '{agent.name}' failed: {e}")
                logger.error(traceback.format_exc())
                raise


