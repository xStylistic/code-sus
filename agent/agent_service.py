class CodingTask(BaseModel):
    """An OOP coding task generated by AI for codemates to solve."""
    title: str = Field(description="Short task title, e.g. 'Fix the Inheritance Chain'")
    prompt: str = Field(description="2-3 sentence task description telling the player what to implement or fix")
    starter_code: str = Field(description="Starter code with gaps/bugs for the player to fix. Include comments like // TODO or # TODO to guide the player")
    solution_code: str = Field(description="The fully correct solution code")
    visible_checks: List[str] = Field(description="3 human-readable check descriptions that describe what the code must do")
    validation_patterns: List[str] = Field(description="3 key code fragments that MUST appear in a correct solution, used for automated validation")


class ImposterHint(BaseModel):
    """A single sabotage code suggestion for the imposter."""
    code_snippet: str = Field(description="The full code to replace the current editor contents with. Must be syntactically valid but subtly inefficient or use bad practices")
    bad_practice: str = Field(description="1-2 sentence explanation of why this code is bad practice or inefficient, written as a tip for the imposter")


class ImposterHints(BaseModel):
    """A single sabotage suggestion for a task."""
    hints: List[ImposterHint] = Field(description="Exactly 1 sabotage suggestion with bad-practice code")


class CodeVerification(BaseModel):
    """AI verification result for submitted code."""
    is_correct: bool = Field(description="Whether the code correctly implements the OOP concept described in the task")
    explanation: str = Field(description="1-2 sentence explanation of why the code is correct or what's wrong")
    issues: List[str] = Field(description="List of bad practices or code smells found. Just name the issue, do NOT explain how to fix it. Empty list if code is perfect")
    fixes: List[str] = Field(description="For each issue, a concrete explanation of how to fix it. Same order as issues list. Empty if no issues")


class MeetingInsight(BaseModel):
    """AI-generated discussion points for emergency meetings."""
    suspicious_behaviors: List[str] = Field(description="2-3 observations about potentially suspicious player behavior based on activity data")
    discussion_prompts: List[str] = Field(description="2-3 questions players should discuss during the meeting")
    tip: str = Field(description="A brief strategic tip for the crew")


